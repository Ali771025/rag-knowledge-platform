"""Prompt orchestration package boundary.

Owns prompt-shaping coordination only:
- accepts normalized prompt requests from upstream application layers
- composes prompt payloads from external context providers
- emits finalized inference payloads to downstream inference adapters

Must not implement:
- retrieval/search logic (owned by `app.rag`)
- memory/session persistence (owned by `app.conversation_memory` + repositories)
- user identity/profile CRUD (owned by user management services)
- HTTP/API transport concerns (owned by API gateway/routes)
- model/provider transport execution (owned by LLM inference adapters)
"""

